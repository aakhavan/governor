"""Render ``evaluation/eval_report.md`` from the four report JSONs.

    uv run python -m governor.eval.report

Reads ``<system>-<split>.json`` for baseline/agent x tune/holdout and writes
one Markdown file: the summary table, per-category results, and an error
taxonomy of the agent's holdout failures. Every number comes from the JSONs;
nothing is re-run. Failures are classified by rule from the item's expect,
behaviour and reason; ``taxonomy.yaml`` next to the reports can override the
class and add a one-line note per item (a human reading the SQL).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import yaml

from governor.core import paths

DEFAULT_REPORTS = paths.ROOT / "evaluation" / "reports"
DEFAULT_OUT = paths.ROOT / "evaluation" / "eval_report.md"
DEFAULT_HOLDOUT_LOG = paths.ROOT / "evaluation" / "holdout_runs.log"
SYSTEMS = ("baseline", "agent")
SPLITS = ("tune", "holdout")
CLASSES = (
    "wrong grain",
    "wrong filter",
    "wrong join",
    "missed clarification",
    "over-clarification",
    "policy",
    "other",
)
ROWS = (
    ("execution accuracy", "execution_accuracy"),
    ("valid SQL, first attempt", "valid_sql_first"),
    ("valid SQL, final", "valid_sql_final"),
    ("clarify precision", "clarify_precision"),
    ("clarify recall", "clarify_recall"),
    ("policy compliance", "policy_compliance"),
    ("PII leak", "pii_leak"),
    ("cost (USD)", "cost_usd"),
    ("latency p50 (s)", "latency_s_p50"),
)


def fmt(value: Any) -> str:
    """3 decimals for numbers, ``-`` for null (an empty denominator)."""
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return f"{value:.3f}"
    return str(value)


def load_reports(directory: Path) -> dict[tuple[str, str], dict]:
    """All four reports; a missing one is an error (the table would lie)."""
    reports = {}
    for system in SYSTEMS:
        for split in SPLITS:
            path = directory / f"{system}-{split}.json"
            if not path.is_file():
                raise FileNotFoundError(f"missing report {path}")
            reports[(system, split)] = json.loads(path.read_text(encoding="utf-8"))
    return reports


def load_annotations(path: Path) -> dict[str, dict]:
    """``{item id: {class, note}}`` from taxonomy.yaml, empty when absent."""
    if not path.is_file():
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {str(k): dict(v) for k, v in data.items()}


def classify(item: dict) -> str:
    """The rule-based class of one failed item."""
    expect, behaviour, reason = item["expect"], item["behaviour"], item.get("reason") or ""
    if expect == "clarify" and behaviour != "clarify":
        return "missed clarification"
    if behaviour == "clarify" and expect != "clarify":
        return "over-clarification"
    if item["category"] == "policy" or item.get("leak"):
        return "policy"
    if "column count" in reason:
        return "wrong grain"
    if "row count" in reason:
        return "wrong filter"
    return "other"


def failures(report: dict, annotations: dict[str, dict]) -> list[dict]:
    """Failed (or leaking) items with their class and note."""
    out = []
    for item in report["items"]:
        if item["correct"] and not item.get("leak"):
            continue
        note = annotations.get(item["id"], {})
        cls = note.get("class") or classify(item)
        if cls not in CLASSES:
            raise ValueError(f"{item['id']}: unknown class {cls!r}")
        out.append({**item, "class": cls, "note": note.get("note") or item.get("reason") or ""})
    return out


def per_category(report: dict) -> dict[str, tuple[int, int]]:
    counts: dict[str, list[int]] = {}
    for item in report["items"]:
        c = counts.setdefault(item["category"], [0, 0])
        c[0] += bool(item["correct"])
        c[1] += 1
    return {k: (v[0], v[1]) for k, v in counts.items()}


def render(reports: dict[tuple[str, str], dict], annotations: dict[str, dict], holdout_log: str = "") -> str:
    cols = [(s, sp) for sp in SPLITS for s in SYSTEMS]
    any_rep = reports[cols[0]]
    lines = [
        "# Evaluation report",
        "",
        "Generated by `python -m governor.eval.report` from the four JSONs in `evaluation/reports/`. "
        "Do not edit by hand.",
        "",
        f"- as_of: `{any_rep.get('as_of')}`; golden sha256: `{str(any_rep.get('golden_sha'))[:16]}…`",
        "- " + "; ".join(f"{s} {sp}: n={reports[(s, sp)]['summary']['n']}, llm={reports[(s, sp)].get('llm', '?')}"
                         for s, sp in cols),
        "- Prompts frozen in `evaluation/reports/PROMPTS_FROZEN.sha256` before the holdout; "
        "holdout run once per system (log below).",
        "",
        "## Summary",
        "",
        "| metric | " + " | ".join(f"{s} {sp}" for s, sp in cols) + " |",
        "|---|" + "---|" * len(cols),
    ]
    for label, key in ROWS:
        lines.append(f"| {label} | " + " | ".join(fmt(reports[c]["summary"].get(key)) for c in cols) + " |")
    total = sum(r["summary"].get("cost_usd") or 0 for r in reports.values())
    lines += [
        "",
        f"Total model cost of the four runs: ${total:.3f}.",
        "",
        "Execution accuracy is over items that expect an answer (answer, aggregate, mask). "
        "Valid SQL is over items where the system wrote SQL; the baseline writes one query, "
        "so its first and final are the same. A dash is an empty denominator.",
        "",
        "## Per category",
        "",
        "Correct / items. For answer items correct means the result matches the gold rows; "
        "for clarify, refuse and unanswerable items it means the expected behaviour.",
        "",
        "| category | " + " | ".join(f"{s} {sp}" for s, sp in cols) + " |",
        "|---|" + "---|" * len(cols),
    ]
    cats = {c: per_category(reports[c]) for c in cols}
    names = sorted({k for v in cats.values() for k in v})
    for name in names:
        cells = []
        for c in cols:
            hit, n = cats[c].get(name, (0, 0))
            cells.append(f"{hit}/{n}" if n else "-")
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    for split in SPLITS:
        base, agent = cats[("baseline", split)], cats[("agent", split)]
        lost = [f"{k} ({agent[k][0]}/{agent[k][1]} vs {base[k][0]}/{base[k][1]})"
                for k in names if k in base and k in agent and agent[k][0] < base[k][0]]
        lines.append("")
        lines.append(f"Agent loses to the baseline on {split}: " + (", ".join(lost) if lost else "no category") + ".")

    agent_fail = failures(reports[("agent", "holdout")], annotations)
    lines += ["", "## Agent holdout failures", ""]
    if not agent_fail:
        lines.append("None.")
    else:
        lines += ["| class | count |", "|---|---|"]
        for cls in CLASSES:
            n = sum(f["class"] == cls for f in agent_fail)
            lines.append(f"| {cls} | {n} |")
        lines += [""]
        for f in agent_fail:
            lines.append(f"- `{f['id']}` ({f['category']}, {f['role']}), {f['class']}: {f['note']}")

    base_fail = failures(reports[("baseline", "holdout")], {})
    lines += ["", "## Baseline holdout failures (rule-based class)", ""]
    for f in base_fail or []:
        leak = ", PII leak" if f.get("leak") else ""
        lines.append(f"- `{f['id']}` ({f['category']}, {f['role']}), {f['class']}{leak}: {f.get('reason') or ''}")
    if not base_fail:
        lines.append("None.")

    if holdout_log.strip():
        lines += ["", "## Holdout log", "", "```", holdout_log.strip(), "```"]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m governor.eval.report", description=__doc__.splitlines()[0])
    parser.add_argument("--reports", type=Path, default=DEFAULT_REPORTS)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--holdout-log", type=Path, default=DEFAULT_HOLDOUT_LOG)
    args = parser.parse_args(argv)
    reports = load_reports(args.reports)
    annotations = load_annotations(args.reports / "taxonomy.yaml")
    log = args.holdout_log.read_text(encoding="utf-8") if args.holdout_log.is_file() else ""
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(reports, annotations, log), encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
